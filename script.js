function createTimelineGame() {

    const container =
        document.getElementById("sortableEvents");

    container.innerHTML = "";

    const shuffled =
        [...timelineData]
            .sort(() => Math.random() - 0.5);

    shuffled.forEach(period => {

        const item =
            document.createElement("div");

        item.className =
            "sortable-item";

        item.draggable = true;

        item.dataset.id =
            period.id;

        item.innerHTML = `
            <strong>${period.year}</strong>
            —
            ${period.title}
        `;

        addDragEvents(item);

        container.appendChild(item);

    });

}


function addDragEvents(item) {

    item.addEventListener(
        "dragstart",
        () => {

            item.classList.add("dragging");

        }
    );


    item.addEventListener(
        "dragend",
        () => {

            item.classList.remove("dragging");

        }
    );


    item.addEventListener(
        "dragover",
        event => {

            event.preventDefault();

            const dragging =
                document.querySelector(
                    ".dragging"
                );

            if (
                dragging &&
                dragging !== item
            ) {

                const rect =
                    item.getBoundingClientRect();

                const after =
                    event.clientY >
                    rect.top +
                    rect.height / 2;

                const container =
                    item.parentElement;

                if (after) {

                    container.insertBefore(
                        dragging,
                        item.nextSibling
                    );

                } else {

                    container.insertBefore(
                        dragging,
                        item
                    );

                }

            }

        }
    );

}


function checkTimeline() {

    const items =
        document.querySelectorAll(
            ".sortable-item"
        );

    const order =
        Array.from(items)
            .map(item =>
                Number(item.dataset.id)
            );

    const correct =
        timelineData.map(
            period => period.id
        );

    const isCorrect =
        order.every(
            (value, index) =>
                value === correct[index]
        );

    const feedback =
        document.getElementById(
            "timelineFeedback"
        );


    if (isCorrect) {

        feedback.innerHTML = `
            <strong>TYDLYN VOLTOOI.</strong>
            Jy het die historiese keerpunte
            in die korrekte volgorde geplaas.
        `;

    } else {

        feedback.innerHTML = `
            <strong>Byna.</strong>
            Begin by die vroegste ontwikkeling
            en beweeg stap vir stap vorentoe
            deur die tyd.
        `;

    }

}


