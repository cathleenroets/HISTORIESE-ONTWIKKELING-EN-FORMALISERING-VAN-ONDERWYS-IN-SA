function showFinalQuestion() {

    const question =
        finalQuiz[finalQuizIndex];

    document
        .getElementById("finalQuizProgress")
        .textContent =
        `Vraag ${finalQuizIndex + 1} van ${finalQuiz.length}`;


    document
        .getElementById("finalQuizQuestion")
        .textContent =
        question.question;


    const options =
        document.getElementById(
            "finalQuizOptions"
        );

    options.innerHTML = "";


    question.options.forEach(
        (option, index) => {

            const button =
                document.createElement("button");

            button.className =
                "final-option";

            button.textContent =
                option;

            button.addEventListener(
                "click",
                () => answerFinalQuestion(index)
            );

            options.appendChild(button);

        }
    );


    document
        .getElementById("finalQuizFeedback")
        .innerHTML = "";


    document
        .getElementById("nextFinalQuestion")
        .classList.add("hidden");

}


function answerFinalQuestion(selected) {

    const question =
        finalQuiz[finalQuizIndex];

    const buttons =
        document.querySelectorAll(
            ".final-option"
        );


    buttons.forEach(button => {
        button.disabled = true;
    });


    if (selected === question.answer) {

        buttons[selected]
            .classList.add("correct");

        finalQuizScore++;

        document
            .getElementById(
                "finalQuizFeedback"
            )
            .innerHTML =
            `<strong>Reg.</strong> ${question.explanation}`;

    } else {

        buttons[selected]
            .classList.add("wrong");

        buttons[question.answer]
            .classList.add("correct");

        document
            .getElementById(
                "finalQuizFeedback"
            )
            .innerHTML =
            `<strong>Nie heeltemal nie.</strong> ${question.explanation}`;

    }


    document
        .getElementById(
            "nextFinalQuestion"
        )
        .classList.remove("hidden");

}


function nextFinalQuizQuestion() {

    finalQuizIndex++;

    if (
        finalQuizIndex >=
        finalQuiz.length
    ) {

        showResults();

        return;
    }

    showFinalQuestion();

}


